const { chromium } = require('playwright');
const out = process.argv[2];
(async () => {
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const errs = [];
  p.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  await p.goto((process.env.BASE || 'http://localhost:3000') + '/?q=low');
  await p.waitForFunction(() => getComputedStyle(document.querySelector('[role=status]')).display === 'none', null, { timeout: 60000 });
  await p.waitForTimeout(3000);
  await p.screenshot({ path: `${out}/n1-home.png`, timeout: 90000 });
  await p.evaluate(() => { document.querySelector('canvas').__marker = 'persist-me'; window.__ctxLost = 0; document.querySelector('canvas').addEventListener('webglcontextlost', () => window.__ctxLost++); });
  await p.click('header >> text=Pricing');
  await p.waitForTimeout(450); await p.screenshot({ path: `${out}/n2-slicing.png`, timeout: 90000 });
  await p.waitForTimeout(3200); await p.screenshot({ path: `${out}/n3-pricing.png`, timeout: 90000 });
  console.log('url', p.url(), 'canvas persisted:', await p.evaluate(() => document.querySelector('canvas').__marker === 'persist-me' && window.__ctxLost === 0), 'canvases:', await p.evaluate(() => document.querySelectorAll('canvas').length));
  await p.click('header >> text=Book audit');
  await p.waitForTimeout(3500); await p.screenshot({ path: `${out}/n4-booking.png`, timeout: 90000 });
  console.log('url', p.url(), 'canvas persisted:', await p.evaluate(() => document.querySelector('canvas').__marker === 'persist-me'));
  await p.goBack();
  await p.waitForTimeout(3500); await p.screenshot({ path: `${out}/n5-back.png`, timeout: 90000 });
  console.log('url', p.url(), 'canvas persisted:', await p.evaluate(() => document.querySelector('canvas').__marker === 'persist-me'));
  await p.click('header >> text=Agents');
  await p.waitForTimeout(5000); await p.screenshot({ path: `${out}/n6-home-agents.png`, timeout: 90000 });
  console.log('url', p.url(), 'scrollY', await p.evaluate(() => scrollY));
  console.log('errors:', errs.join('\n') || 'none');
  await b.close();
})();
